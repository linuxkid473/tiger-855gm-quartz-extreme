#!/usr/bin/env python3
"""Generate PATCH_TABLES.md from a chain of kext executables.
usage: gen_patch_tables.py out.md name=file name=file ...   (files in chain order, first is the baseline)
Offsets are file offsets; text vm = file offset - 732.  Runs closer than 8 bytes are merged; long runs are truncated."""
import sys, hashlib
out = sys.argv[1]
chain = [a.split('=', 1) for a in sys.argv[2:]]
data = [(n, open(p, 'rb').read()) for n, p in chain]
L = []
L.append('# Exact binary patch tables for `AppleIntel830` (generated by tools/gen_patch_tables.py)\n')
L.append('All offsets are **file offsets** into the kext executable (`Contents/MacOS/AppleIntel830`); for `__text` code the virtual address used in the docs is `file offset - 732` (0x2dc). Runs closer than 8 bytes are merged; long runs (code caves) are truncated - the generator scripts `abi-port/mk_p45.py` ... `mk_p52` contain the full commented source.\n')
L.append('Apple\'s binaries are **not** included in this repository. The chain starts at the output of the ABI translation stage (`abiport.py`) applied to the DTK 10.4.1 kext.\n')
L.append('| version | size | md5 |\n|---|---|---|')
for n, d in data:
    L.append('| %s | %d | `%s` |' % (n, len(d), hashlib.md5(d).hexdigest()))
L.append('')
def runs(a, b):
    r = []; i = 0; n = min(len(a), len(b))
    while i < n:
        if a[i] != b[i]:
            s = i; e = i + 1; last = i
            while e < n and e - last <= 8:
                if a[e] != b[e]: last = e
                e += 1
            r.append((s, last + 1)); i = last + 1
        else: i += 1
    return r
def hx(x, lim=24):
    h = ' '.join('%02x' % c for c in x[:lim])
    return h + (' ... (%d bytes)' % len(x) if len(x) > lim else '')
for (n1, a), (n2, b) in zip(data, data[1:]):
    rs = runs(a, b)
    L.append('\n## %s -> %s  (%d changed regions)\n' % (n1, n2, len(rs)))
    L.append('| file offset | text vm | old bytes | new bytes |\n|---|---|---|---|')
    for s, e in rs:
        L.append('| 0x%x | 0x%x | `%s` | `%s` |' % (s, s - 732, hx(a[s:e]), hx(b[s:e])))
open(out, 'w').write('\n'.join(L) + '\n')
print('wrote', out)
