/* Port of IGT's gen2_render_copyfunc (lib/rendercopy_i830.c): textured RECTLIST copy of a 64x64 texture onto a 64x64 target.
   Output: "B hex" per dword, "R idx bo delta" per relocation (bo 0 = target, bo 1 = texture), "P W H pitch". */
#include <stdio.h>
#include <stdint.h>
#include <string.h>
#include "igt_i830_reg.h"
#define TB0C_LAST_STAGE	(1 << 31)
#define TB0C_RESULT_SCALE_1X		(0 << 29)
#define TB0C_OP_ARG1			(1 << 25)
#define TB0C_OUTPUT_WRITE_CURRENT	(0 << 24)
#define TB0C_ARG1_SEL_TEXEL0		(6 << 6)
#define TB0A_RESULT_SCALE_1X		(0 << 29)
#define TB0A_OP_ARG1			(1 << 25)
#define TB0A_OUTPUT_WRITE_CURRENT	(0<<24)
#define TB0A_ARG1_SEL_TEXEL0		(6 << 6)
static uint32_t b[512]; static int n; static struct { int idx, bo, delta; } rl[8]; static int nr;
#define OUT(x) (b[n++] = (uint32_t)(x))
#define RELOC(BO, D) do { rl[nr].idx = n; rl[nr].bo = (BO); rl[nr].delta = (D); nr++; OUT(0); } while (0)
static void vf(float f) { uint32_t u; memcpy(&u, &f, 4); OUT(u); }
int main(void)
{
   const int W = 64, H = 64, tw = 64, th = 64, dpitch = 256, tpitch = 256;
   /* gen2_emit_invariant */
   for (int i = 0; i < 4; i++) {
      OUT(_3DSTATE_MAP_CUBE | MAP_UNIT(i));
      OUT(_3DSTATE_MAP_TEX_STREAM_CMD | MAP_UNIT(i) | DISABLE_TEX_STREAM_BUMP | ENABLE_TEX_STREAM_COORD_SET |
          TEX_STREAM_COORD_SET(i) | ENABLE_TEX_STREAM_MAP_IDX | TEX_STREAM_MAP_IDX(i));
      OUT(_3DSTATE_MAP_COORD_TRANSFORM);
      OUT(DISABLE_TEX_TRANSFORM | TEXTURE_SET(i));
   }
   OUT(_3DSTATE_MAP_COORD_SETBIND_CMD);
   OUT(TEXBIND_SET3(TEXCOORDSRC_VTXSET_3) | TEXBIND_SET2(TEXCOORDSRC_VTXSET_2) | TEXBIND_SET1(TEXCOORDSRC_VTXSET_1) | TEXBIND_SET0(TEXCOORDSRC_VTXSET_0));
   OUT(_3DSTATE_SCISSOR_ENABLE_CMD | DISABLE_SCISSOR_RECT);
   OUT(_3DSTATE_VERTEX_TRANSFORM);
   OUT(DISABLE_VIEWPORT_TRANSFORM | DISABLE_PERSPECTIVE_DIVIDE);
   OUT(_3DSTATE_W_STATE_CMD); OUT(MAGIC_W_STATE_DWORD1); OUT(0x3f800000);
   OUT(_3DSTATE_INDPT_ALPHA_BLEND_CMD | DISABLE_INDPT_ALPHA_BLEND | ENABLE_ALPHA_BLENDFUNC | ABLENDFUNC_ADD);
   OUT(_3DSTATE_CONST_BLEND_COLOR_CMD); OUT(0);
   OUT(_3DSTATE_MODES_1_CMD | ENABLE_COLR_BLND_FUNC | BLENDFUNC_ADD | ENABLE_SRC_BLND_FACTOR | SRC_BLND_FACT(BLENDFACTOR_ONE) |
       ENABLE_DST_BLND_FACTOR | DST_BLND_FACT(BLENDFACTOR_ZERO));
   OUT(_3DSTATE_ENABLES_1_CMD | DISABLE_LOGIC_OP | DISABLE_STENCIL_TEST | DISABLE_DEPTH_BIAS | DISABLE_SPEC_ADD | DISABLE_FOG |
       DISABLE_ALPHA_TEST | DISABLE_DEPTH_TEST | ENABLE_COLOR_BLEND);
   OUT(_3DSTATE_ENABLES_2_CMD | DISABLE_STENCIL_WRITE | DISABLE_DITHER | DISABLE_DEPTH_WRITE | ENABLE_COLOR_MASK | ENABLE_COLOR_WRITE | ENABLE_TEX_CACHE);
   /* gen2_emit_copy_pipeline */
   OUT(_3DSTATE_INDPT_ALPHA_BLEND_CMD | DISABLE_INDPT_ALPHA_BLEND);
   OUT(_3DSTATE_ENABLES_1_CMD | DISABLE_LOGIC_OP | DISABLE_STENCIL_TEST | DISABLE_DEPTH_BIAS | DISABLE_SPEC_ADD | DISABLE_FOG |
       DISABLE_ALPHA_TEST | DISABLE_COLOR_BLEND | DISABLE_DEPTH_TEST);
   OUT(_3DSTATE_LOAD_STATE_IMMEDIATE_2 | LOAD_TEXTURE_BLEND_STAGE(0) | 1);
   OUT(TB0C_LAST_STAGE | TB0C_RESULT_SCALE_1X | TB0C_OUTPUT_WRITE_CURRENT | TB0C_OP_ARG1 | TB0C_ARG1_SEL_TEXEL0);
   OUT(TB0A_RESULT_SCALE_1X | TB0A_OUTPUT_WRITE_CURRENT | TB0A_OP_ARG1 | TB0A_ARG1_SEL_TEXEL0);
   /* gen2_emit_target */
   OUT(_3DSTATE_BUF_INFO_CMD);
   OUT(BUF_3D_ID_COLOR_BACK | BUF_3D_PITCH(dpitch));
   RELOC(0, 0);
   OUT(_3DSTATE_DST_BUF_VARS_CMD);
   OUT(COLR_BUF_ARGB8888 | DSTORG_HORT_BIAS(0x8) | DSTORG_VERT_BIAS(0x8));
   OUT(_3DSTATE_DRAW_RECT_CMD); OUT(0); OUT(0); OUT(DRAW_YMAX(H - 1) | DRAW_XMAX(W - 1)); OUT(0);
   /* gen2_emit_texture */
   OUT(_3DSTATE_LOAD_STATE_IMMEDIATE_2 | LOAD_TEXTURE_MAP(0) | 4);
   RELOC(1, 0);
   OUT(((th - 1) << TM0S1_HEIGHT_SHIFT) | ((tw - 1) << TM0S1_WIDTH_SHIFT) | MAPSURF_32BIT | MT_32BIT_ARGB8888);
   OUT(((tpitch / 4 - 1) << TM0S2_PITCH_SHIFT) | TM0S2_MAP_2D);
   OUT((FILTER_NEAREST << TM0S3_MAG_FILTER_SHIFT) | (FILTER_NEAREST << TM0S3_MIN_FILTER_SHIFT) | (MIPFILTER_NONE << TM0S3_MIP_FILTER_SHIFT));
   OUT(0);
   OUT(_3DSTATE_MAP_COORD_SET_CMD | TEXCOORD_SET(0) | ENABLE_TEXCOORD_PARAMS | TEXCOORDS_ARE_NORMAL | TEXCOORDTYPE_CARTESIAN |
       ENABLE_ADDR_V_CNTL | TEXCOORD_ADDR_V_MODE(TEXCOORDMODE_CLAMP_BORDER) | ENABLE_ADDR_U_CNTL | TEXCOORD_ADDR_U_MODE(TEXCOORDMODE_CLAMP_BORDER));
   OUT(_3DSTATE_LOAD_STATE_IMMEDIATE_1 | I1_LOAD_S(2) | I1_LOAD_S(3) | I1_LOAD_S(8) | 2);
   OUT(1 << 12);
   OUT(S3_CULLMODE_NONE | S3_VERTEXHAS_XY);
   OUT(S8_ENABLE_COLOR_BUFFER_WRITE);
   OUT(_3DSTATE_VERTEX_FORMAT_2_CMD | TEXCOORDFMT_2D << 0);
   OUT(PRIM3D_INLINE | PRIM3D_RECTLIST | (3 * 4 - 1));
   vf(W); vf(H); vf(1.0f); vf(1.0f);
   vf(0); vf(H); vf(0.0f); vf(1.0f);
   vf(0); vf(0); vf(0.0f); vf(0.0f);
   OUT(0x02000001); OUT(0x05000000);
   if (n & 1) OUT(0);
   for (int i = 0; i < n; i++) printf("B %08x\n", b[i]);
   for (int i = 0; i < nr; i++) printf("R %d %d %d\n", rl[i].idx, rl[i].bo, rl[i].delta);
   printf("P %d %d %d\n", W, H, dpitch);
   return 0;
}
